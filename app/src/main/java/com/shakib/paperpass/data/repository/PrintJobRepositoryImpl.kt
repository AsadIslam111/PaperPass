package com.shakib.paperpass.data.repository

import com.shakib.paperpass.core.util.Resource
import com.shakib.paperpass.data.local.dao.PrintJobDao
import com.shakib.paperpass.data.local.dao.QuotaDao
import com.shakib.paperpass.data.local.entity.PrintJobEntity
import com.shakib.paperpass.data.network.ipp.IppPrintClient
import com.shakib.paperpass.domain.model.PrintJob
import com.shakib.paperpass.domain.model.PrintJobStatus
import com.shakib.paperpass.domain.model.Printer
import com.shakib.paperpass.domain.model.User
import com.shakib.paperpass.domain.model.UserRole
import com.shakib.paperpass.domain.repository.PrintJobRepository
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map
import java.io.InputStream

class PrintJobRepositoryImpl(
    private val printJobDao: PrintJobDao,
    private val quotaDao: QuotaDao,
    private val ippClient: IppPrintClient
) : PrintJobRepository {

    override fun getAllJobsFlow(): Flow<List<PrintJob>> {
        return printJobDao.getAllJobsFlow().map { list -> list.map { it.toDomain() } }
    }

    override fun getJobsForUserFlow(userId: Long): Flow<List<PrintJob>> {
        return printJobDao.getJobsForUserFlow(userId).map { list -> list.map { it.toDomain() } }
    }

    override fun getPendingRequestsFlow(): Flow<List<PrintJob>> {
        return printJobDao.getPendingRequestsFlow().map { list -> list.map { it.toDomain() } }
    }

    override suspend fun submitJob(
        user: User,
        printer: Printer,
        documentName: String,
        pageCount: Int,
        copies: Int,
        isColor: Boolean,
        isDuplex: Boolean,
        documentStream: InputStream?
    ): Resource<PrintJob> {
        val totalPages = pageCount * copies

        // 1. Check Quota (Admins bypass quota)
        if (user.role != UserRole.ADMIN) {
            val quota = quotaDao.getQuotaByUserId(user.id)
            if (quota != null) {
                if (quota.pagesUsedToday + totalPages > quota.dailyLimit) {
                    return Resource.Error("Daily quota exceeded! Needed: $totalPages, Remaining: ${quota.dailyLimit - quota.pagesUsedToday}")
                }
                if (quota.pagesUsedMonth + totalPages > quota.monthlyLimit) {
                    return Resource.Error("Monthly quota exceeded! Limit is ${quota.monthlyLimit} pages.")
                }
            }
        }

        // 2. Department Restriction Check
        if (printer.departmentRestriction != "ALL" &&
            user.role != UserRole.ADMIN &&
            printer.departmentRestriction != user.department
        ) {
            return Resource.Error("Access Denied: This printer is restricted to '${printer.departmentRestriction}' department.")
        }

        // 3. Determine Initial Status
        // Guests go into PENDING queue for admin review; Employees & Admins print immediately
        val initialStatus = if (user.role == UserRole.GUEST) {
            PrintJobStatus.PENDING
        } else {
            PrintJobStatus.APPROVED
        }

        val jobEntity = PrintJobEntity(
            userId = user.id,
            printerId = printer.id,
            userName = user.fullName,
            printerName = printer.name,
            documentName = documentName,
            pageCount = pageCount,
            copies = copies,
            isColor = isColor,
            isDuplex = isDuplex,
            status = initialStatus.name
        )

        val jobId = printJobDao.insertJob(jobEntity)
        val createdJob = jobEntity.copy(id = jobId).toDomain()

        if (user.role == UserRole.GUEST) {
            return Resource.Success(createdJob)
        }

        // 4. Dispatch Job to Printer via IPP
        printJobDao.updateJobStatus(jobId, PrintJobStatus.PRINTING.name)

        val stream = documentStream ?: "Sample Printed Document Content\nGenerated by PaperPass\nUser: ${user.fullName}\n".byteInputStream()
        val result = ippClient.sendIppJob(
            printerIp = printer.ipAddress,
            port = printer.port,
            jobName = documentName,
            userName = user.employeeId,
            documentStream = stream
        )

        return when (result) {
            is IppPrintClient.PrintResult.Success -> {
                // Deduct quota
                quotaDao.deductQuota(user.id, totalPages)
                printJobDao.updateJobStatus(jobId, PrintJobStatus.COMPLETED.name, System.currentTimeMillis())
                Resource.Success(createdJob.copy(status = PrintJobStatus.COMPLETED))
            }
            is IppPrintClient.PrintResult.Failure -> {
                printJobDao.updateJobStatus(jobId, PrintJobStatus.FAILED.name, System.currentTimeMillis(), result.error)
                Resource.Error("Printer transmission error: ${result.error}")
            }
        }
    }

    override suspend fun approveJob(jobId: Long): Resource<Unit> {
        val job = printJobDao.getJobById(jobId) ?: return Resource.Error("Job not found")
        val totalPages = job.pageCount * job.copies

        // Deduct guest quota
        quotaDao.deductQuota(job.userId, totalPages)
        printJobDao.updateJobStatus(jobId, PrintJobStatus.COMPLETED.name, System.currentTimeMillis())
        return Resource.Success(Unit)
    }

    override suspend fun rejectJob(jobId: Long, reason: String): Resource<Unit> {
        printJobDao.updateJobStatus(jobId, PrintJobStatus.REJECTED.name, System.currentTimeMillis(), reason)
        return Resource.Success(Unit)
    }
}

